#!/usr/bin/env bash
# Plint · AMP (CubeCoders) — installed natively, the officially supported way.
# The installer is interactive: it asks for the panel admin user/password and
# which dependencies to pull in. Answer "no" to HTTPS; Caddy handles that.
set -euo pipefail
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"
need_root; load_env

step "Game servers (AMP)"

if id amp >/dev/null 2>&1 && command -v ampinstmgr >/dev/null 2>&1; then
  ok "AMP is already installed (user 'amp'). Skipping the installer."
else
  cat <<EOF
${C_DIM}The official CubeCoders installer runs now. Suggested answers:
  · System password        → just press Enter (auto-generated)
  · Username / password    → the AMP panel login you want
  · Minecraft dependencies → yes
  · SteamCMD               → yes if you'll run Steam games
  · Docker isolation       → yes
  · HTTPS                  → NO  (Caddy provides https://games.${DOMAIN})
Then finish in the browser at https://games.${DOMAIN} with your licence key.${C_RESET}

EOF
  read -r -p "Press Enter to start the AMP installer (or Ctrl+C to skip) " _
  bash <(wget -qO- getamp.sh)
fi

# Back up AMP's data with everything else.
if [[ -d /home/amp/.ampdata ]]; then
  cat > "${PLINT_DIR}/stacks/ops/compose.override.yaml" <<'EOF'
# generated by scripts/amp-install.sh — AMP data for Kopia
services:
  kopia:
    volumes:
      - /home/amp/.ampdata:/sources/amp:ro
EOF
  compose ops up -d kopia >/dev/null 2>&1 || true
fi

cat <<EOF

${C_BOLD}After first login to AMP:${C_RESET}
  Configuration → Instance Deployment → set "Default Instance IP Binding" to ${SERVER_IP}
  Configuration → Security & Privacy → turn on "Using Reverse Proxy" if links misbehave.
EOF
ok "AMP at https://games.${DOMAIN}"
