"""``twin bench``: what a simulation costs, per simulated second and per level of the loop, and what its outputs
cost (docs/performance.md, architecture 20).

Each chosen example project (``examples/<name>``, a project folder or file; ``--all``: every example) runs
headless in its own subprocess, capped like bin/tsafe (cnctwin.core.outputs.capped_command: a systemd scope,
else RLIMIT_DATA) with the deterministic environment. The subprocess measures:

* wall time, process CPU time, simulated time (run.json ``summary.cycle_time_s``, else the last
  ``sim_time_s`` the loop reported), peak resident memory;
* CPU per level, by an instrumenting profiler: the loop's level functions (:data:`LEVEL_TABLE`, plus every
  domain's ``macro_step`` / ``absorb`` / ``end_operation`` / ``finalize`` found in ``cnctwin.<domain>.domain``)
  are wrapped with a timer that books each call's process CPU time to its level exclusively (a nested call of
  another level is booked to that level, not twice). The compiled macro step ``run_macro`` holds L1 (servo,
  kinematics, broad phase) and L0 in one call: its CPU per L1 tick in the calls without an L0 step (the tool
  out of contact: L1 alone) estimates the L1 share of every call, the rest is the hot loop. CPU before the
  first level call is the setup (project, databases, kernel loading or compiling), CPU not in a level while
  the loop runs is ``other``;
* with ``--outputs``, finalize_outputs on the run directory, per generator.

``--max-sim-s S`` stops a run after S simulated seconds (the progress callback raises :class:`BenchStop`, a
BaseException the loop lets pass, at a macro-step boundary). The engine is cnctwin.core.loop.run_project
(``--engine loop``, or ``--runner module:function``); without it in the build (``--engine auto``) each operation
runs through cnctwin.core.drive.OperationDriver: controller, motion, the compiled hot loop with cutting, removal
and dynamics; the slow domains and the recording do not run there, and the table says so.
``--outputs-of RUN_DIR`` times finalize_outputs on a copy of an existing run directory.

The results are written into docs/performance.md between its bench markers (the budget table of architecture
20 stays at the top; rows of examples not benchmarked this time are kept).
"""

