def find_examples(names, every: bool) -> list[tuple[str, Path]]:
    """(name, project.yaml) of the examples asked for: names of examples/ folders, project folders or files."""
    root = Path(paths.EXAMPLES)
    if every:
        return [(p.parent.name, p) for p in sorted(root.glob("*/project.yaml"))]
    out = []
    for name in names:
        candidate = Path(name)
        if not candidate.exists():
            candidate = root / name
        project = candidate / "project.yaml" if candidate.is_dir() else candidate
        if not project.is_file():
            known = ", ".join(sorted(p.parent.name for p in root.glob("*/project.yaml")))
            raise SystemExit(f"twin bench: no project {name!r} (examples: {known})")
        out.append((project.parent.name, project.resolve()))
    return out


def _bench_subprocess(spec: dict, work: Path, memory_mode: str, memory_bytes: int, timeout_s: float) -> dict:
    from .core import outputs as O
    mode = O.memory_mode(memory_mode)
    limit = memory_bytes * int(O._params()["rlimit_data_factor"]) if mode == "rlimit" else memory_bytes
    spec_path, result_path, log_path = work / "spec.json", work / "result.json", work / "log.txt"
    spec_path.write_text(json.dumps(spec, sort_keys=True), encoding="utf-8")
    unit = O.unit_name(work, f"bench-{spec['example']}") if mode == "systemd" else None
    command, env = O.capped_command(["-m", "cnctwin.bench", "--child", str(spec_path), "--result", str(result_path),
                                     "--memory-mode", mode, "--memory-bytes", str(limit)], mode, limit, unit)
    poll = float(_params()["poll_interval_s"])
    start = time.perf_counter()
    timed_out = False
    with open(log_path, "wb") as log:
        proc = subprocess.Popen(command, env=env, cwd=str(work), stdin=subprocess.DEVNULL, stdout=log,
                                stderr=subprocess.STDOUT, start_new_session=True)
        try:
            while True:
                try:
                    proc.wait(timeout=poll)
                    break
                except subprocess.TimeoutExpired:
                    if time.perf_counter() - start > timeout_s:
                        timed_out = True
                        O.stop_process(proc, unit, float(O._params()["kill_grace_s"]))
                        break
        except BaseException:
            O.stop_process(proc, unit, float(O._params()["kill_grace_s"]))
            raise
    try:
        result = json.loads(result_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        reason = f"timed out after {timeout_s:.0f} s" if timed_out else O._exit_reason(proc.returncode, mode,
                                                                                         memory_bytes)
        result = {"format": RESULT_FORMAT, "version": 1, "example": spec["example"], "project": spec["project"],
                  "engine": spec.get("engine"), "status": "failed", "error": {"type": "BenchProcess",
                                                                               "message": reason},
                  "log_tail": O._tail(log_path, int(O._params()["log_tail_bytes"])), "machine": _machine(),
                  "date": time.strftime("%Y-%m-%d", time.gmtime())}
    result["memory_mode"], result["memory_bytes"] = mode, memory_bytes
    result["process_wall_s"] = time.perf_counter() - start
    return result


def bench(examples: list[tuple[str, Path]], *, engine: str = "auto", runner: str | None = None,
          max_sim_s: float | None = None, outputs: bool = False, outputs_options: dict | None = None,
          memory_mode: str = "auto", memory_bytes: int | None = None, timeout_s: float | None = None,
          work_dir=None, keep: bool = False, options: dict | None = None, report=None,
          table: dict | None = None) -> list[dict]:
    """Benchmark each example in its own capped subprocess; returns one result per example. ``table``: a level
    table instead of the loop's (:func:`level_table`)."""
    p = _params()
    cap = int(memory_bytes or p["run_memory_max_bytes"])
    limit_s = float(timeout_s or p["run_timeout_s"])
    runner = runner or os.environ.get("CNCTWIN_ENTRY_SIMULATE")       # the subprocess gets a fresh environment
    base = Path(work_dir) if work_dir is not None else Path(tempfile.mkdtemp(prefix="cnctwin-bench-"))
    base.mkdir(parents=True, exist_ok=True)
    results = []
    for name, project in examples:
        work = base / name
        if work.exists():
            shutil.rmtree(work)
        work.mkdir(parents=True)
        spec = {"example": name, "project": str(project), "run_dir": str(work / "run"), "engine": engine,
                "runner": runner, "max_sim_s": max_sim_s, "outputs": outputs, "outputs_options": outputs_options,
                "options": dict(options or {}), "table": table}
        if report is not None:
            report(f"{name}: running ({engine}{f', at most {max_sim_s:g} s simulated' if max_sim_s else ''})")
        result = _bench_subprocess(spec, work, memory_mode, cap, limit_s)
        results.append(result)
        if report is not None:
            report(summary_line(result))
        if not keep:
            shutil.rmtree(work, ignore_errors=True)
    if not keep and work_dir is None:
        shutil.rmtree(base, ignore_errors=True)
    return results


def bench_outputs(run_dirs, options: dict | None = None, report=None) -> list[dict]:
    """finalize_outputs timed on a copy of each run directory (the run itself is not changed)."""
    out = []
    for run_dir in run_dirs:
        run_dir = Path(run_dir)
        with tempfile.TemporaryDirectory(prefix="cnctwin-bench-outputs-") as tmp:
            copy = Path(tmp) / run_dir.name
            shutil.copytree(run_dir, copy, ignore=shutil.ignore_patterns("checkpoints"))
            for name in ("report.html", "report.pdf", "setup_sheet.html", "setup_sheet.pdf", "video.mp4", "audio.wav",
                         "audio.json", "render.json"):
                (copy / name).unlink(missing_ok=True)
            shutil.rmtree(copy / "images", ignore_errors=True)
            timing = outputs_timing(copy, options)
        record = {"run": run_dir.name, "run_dir": str(run_dir), "outputs": timing, "machine": _machine(),
                  "date": time.strftime("%Y-%m-%d", time.gmtime())}
        out.append(record)
        if report is not None:
            report(f"{run_dir.name}: outputs in {timing['wall_s']:.1f} s" + (f", failed: {', '.join(timing['failed'])}"
                                                                            if timing["failed"] else ""))
    return out


def summary_line(result: dict) -> str:
    levels = (result.get("levels") or {}).get("per_sim") or {}
    parts = [f"{result['example']}: {result['status']}", f"engine {result.get('engine')}"]
    if result.get("simulated_s"):
        parts.append(f"{result['simulated_s']:.3f} s simulated in {result.get('wall_s', 0.0):.1f} s wall")
    if result.get("cpu_per_sim") is not None:
        parts.append(f"{result['cpu_per_sim']:.3g} CPU s/s")
    shown = [f"{LEVEL_NAMES[k]} {levels[k]:.3g}" for k in LEVELS if levels.get(k) is not None]
    if shown:
        parts.append("(" + ", ".join(shown) + ")")
    if result.get("peak_rss_bytes"):
        parts.append(f"peak {result['peak_rss_bytes'] / 2 ** 20:.0f} MiB")
    if result.get("error") and result["status"] != "stopped":
        parts.append(f"error: {result['error'].get('type')}: {result['error'].get('message')}")
    return ", ".join(parts)


# =============================================================================== docs/performance.md

def _number(value, digits: int = 3) -> str:
    if value is None or (isinstance(value, float) and not math.isfinite(value)):
        return "-"
    if abs(value) >= 1000 or value == 0:
        return f"{value:.0f}" if abs(value) >= 1000 else "0"
    return f"{value:.{digits}g}"


def _budget_cell(value, budget) -> str:
    text = _number(value)
    if value is not None and budget is not None and value > budget:
        text += " (over)"
    return text


def budget_table() -> str:
    p = _params()
    rows = [("hot loop", p["budget_hot_loop_cpu_per_sim"], "L0 while in contact: element forces, dynamics, removal, "
                                                         "surface memory (compiled)"),
            ("L1", p["budget_l1_cpu_per_sim"], "controller, servo, kinematics, travel and collision checks, broad "
                                              "phase, per-tick recording"),
            ("L2", p["budget_l2_cpu_per_sim"], "the slow domains' macro steps, findings rules, ledgers"),
            ("recording", p["budget_recording_cpu_per_sim"], "series, frames.bin, keyframes, checkpoints, trace")]
    total = sum(r[1] for r in rows)
    lines = ["| level | CPU s per simulated s | what |", "|---|---|---|"]
    lines += [f"| {name} | {_number(value)} | {what} |" for name, value, what in rows]
    lines.append(f"| total | {_number(total)} | tests/perf fails above {_number(p['perf_limit_cpu_per_sim'])} |")
    return "\n".join(lines)


def _doc_header() -> str:
    p = _params()
    return ("# Performance\n\n"
            "Budget (architecture 20): one core of this box, CPU seconds per simulated second, for the reference "
            "pocket (D10 4-flute end mill at 10 000 rpm). The simulation process stays at or below "
            f"{p['simulation_memory_budget_bytes'] / 1e9:.1f} GB for the reference part (architecture 10); reports, "
            "PDF, pictures and video run in separate processes after the simulation (docs/outputs.md).\n\n"
            + budget_table() + "\n\n")


def _doc_method() -> str:
    return ("## How these numbers are measured\n\n"
            "`twin bench` (cnctwin/bench.py) runs each example headless in its own subprocess, capped like "
            "bin/tsafe, with one thread and PYTHONHASHSEED=0. CPU is process CPU time. The levels are booked by an "
            "instrumenting profiler: the loop's level functions are wrapped with a timer that books each call to "
            "its level exclusively (a nested call of another level is booked there). The compiled macro step "
            "(`run_macro`) runs L1 and L0 in one call: its CPU per L1 tick in the calls without an L0 step (tool "
            "out of contact) estimates the L1 share of every call; the rest is the hot loop. *setup* is the CPU "
            "before the first level call (project, databases, loading or compiling the kernels), *other* the CPU "
            "inside the loop in no level, *op ends* the domains' end_operation and finalize (inspection, part "
            "export). Engine *driver*: cnctwin.core.drive.OperationDriver per operation (controller, motion, the "
            "hot loop with cutting, removal and dynamics) while cnctwin.core.loop is not in the build: no slow "
            "domains, no recording, nothing written. Output generation: cnctwin.core.outputs.finalize_outputs, "
            "each generator in its own capped subprocess (wall and CPU seconds, peak resident memory).\n\n")


def _read_doc_data(text: str) -> dict:
    start = text.find(DATA_PREFIX)
    if start < 0:
        return {}
    end = text.find(DATA_SUFFIX, start + len(DATA_PREFIX))
    try:
        data = json.loads(text[start + len(DATA_PREFIX):end])
    except ValueError:
        return {}
    return data if isinstance(data, dict) else {}


def _simulation_table(runs: dict) -> str:
    p = _params()
    budgets = {k: p[v] for k, v in BUDGET_KEYS.items()}
    lines = ["| example | engine | simulated s | wall s | CPU s | CPU s / sim s | hot loop | L1 | L2 | recording | "
             "op ends | other | setup CPU s | peak RSS MiB | status | date |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for key in sorted(runs):
        r = runs[key]
        levels = r.get("levels") or {}
        per = levels.get("per_sim") or {}
        status = r.get("status", "")
        if r.get("status") == "stopped" and r.get("max_sim_s"):
            status = f"stopped at {_number(r['max_sim_s'])} s"
        elif r.get("error") and r.get("status") == "failed":
            status = f"failed: {r['error'].get('type')}"
        lines.append(f"| {r.get('example')} | {r.get('engine')} | {_number(r.get('simulated_s'))} | "
                     f"{_number(r.get('wall_s'))} | {_number(r.get('cpu_s'))} | "
                     f"{_number(levels.get('loop_per_sim'))} | "
                     + " | ".join(_budget_cell(per.get(k), budgets.get(k)) for k in LEVELS) + " | "
                     f"{_number(per.get('other'))} | {_number(levels.get('setup_cpu_s'))} | "
                     f"{_number((r.get('peak_rss_bytes') or 0) / 2 ** 20 or None)} | {status} | {r.get('date', '')} |")
    return "\n".join(lines)


def _outputs_table(outputs: dict) -> str:
    lines = ["| run | generator | status | wall s | CPU s | peak RSS MiB | files | date |",
             "|---|---|---|---|---|---|---|---|"]
    for key in sorted(outputs):
        record = outputs[key]
        for name, g in (record.get("outputs") or {}).get("generators", {}).items():
            rss = (g.get("peak_rss_bytes") or 0) / 2 ** 20 or None
            lines.append(f"| {record.get('run')} | {name} | {g.get('status')} | {_number(g.get('wall_s'))} | "
                         f"{_number(g.get('cpu_s'))} | {_number(rss)} | {g.get('files', '')} | "
                         f"{record.get('date', '')} |")
    return "\n".join(lines)


def write_doc(path, results: list[dict] = (), outputs: list[dict] = ()) -> Path:
    """Merge the results into the bench part of docs/performance.md (rows of runs not in ``results`` are kept);
    a new file starts with the budget table of architecture 20."""
    path = Path(path)
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    data = _read_doc_data(text)
    runs = dict(data.get("runs") or {})
    outs = dict(data.get("outputs") or {})
    for r in results:
        runs[f"{r.get('example')}|{r.get('engine')}"] = {k: r.get(k) for k in (
            "example", "engine", "status", "error", "simulated_s", "wall_s", "cpu_s", "levels", "peak_rss_bytes",
            "max_sim_s", "date", "machine", "not_instrumented")}
        if r.get("outputs"):
            outs[f"{r.get('example')} (bench run)"] = {"run": f"{r.get('example')} (bench run)",
                                                       "outputs": r["outputs"], "date": r.get("date")}
    for o in outputs:
        outs[str(o.get("run"))] = {"run": o.get("run"), "outputs": o.get("outputs"), "date": o.get("date"),
                                   "machine": o.get("machine")}
    machines = sorted({json.dumps(v.get("machine"), sort_keys=True) for v in list(runs.values()) + list(outs.values())
                       if v.get("machine")})
    body = [DOC_BEGIN, "", "## Simulation (twin bench)", ""]
    body.append(_simulation_table(runs) if runs else "No example has been benchmarked yet (`twin bench EXAMPLE`).")
    body += ["", "Per-level columns are CPU seconds per simulated second; *(over)* marks a level above its budget.", ""]
    body += ["## Output generation (finalize_outputs)", ""]
    body.append(_outputs_table(outs) if outs else "No output generation has been timed yet (`twin bench "
                                                   "--outputs-of RUN_DIR`).")
    if machines:
        body += ["", "Measured on: " + "; ".join(", ".join(f"{k} {v}" for k, v in json.loads(m).items())
                                                for m in machines) + "."]
    body += ["", DATA_PREFIX + json.dumps({"runs": runs, "outputs": outs}, sort_keys=True) + DATA_SUFFIX, DOC_END]
    block = "\n".join(body)
    if DOC_BEGIN in text and DOC_END in text:
        head = text[:text.index(DOC_BEGIN)]
        tail = text[text.index(DOC_END) + len(DOC_END):]
        new = head + block + tail
    else:
        new = (text or _doc_header()) + ("" if (text or "").endswith("\n\n") or not text else "\n") + block + "\n\n" \
            + _doc_method()
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(new, encoding="utf-8")
    tmp.replace(path)
    return path


