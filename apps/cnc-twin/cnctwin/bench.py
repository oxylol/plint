def drive_project(project_path, run_dir, options, progress_cb) -> dict:
    """The benchmark's engine without cnctwin.core.loop: every operation through cnctwin.core.drive.OperationDriver
    (controller, motion, the compiled hot loop with cutting, removal and dynamics, their macro steps and the
    ledger's time balance). The slow domains, the recording and the outputs do not run; nothing is written."""
    from .core.drive import OperationDriver
    from .db import Database
    from .project import resolve
    db = Database.load()
    project = resolve(Path(project_path), db)
    elapsed = 0.0
    steps = 0
    for index, operation in enumerate(project.operations):
        driver = OperationDriver(project, op_index=index, db=db)
        while not driver.feeder.finished():
            driver.step()
            steps += 1
            progress_cb({"sim_time_s": elapsed + driver.state.clock.tick * driver.ctx.tick_s,
                         "op": str(operation.name)})
        elapsed += driver.state.clock.tick * driver.ctx.tick_s
    return {"simulated_s": elapsed, "macro_steps": steps}


class _Progress:
    def __init__(self, max_sim_s: float | None) -> None:
        self.max_sim_s = max_sim_s
        self.sim_time_s = 0.0
        self.calls = 0

    def __call__(self, progress=None, **fields) -> None:
        merged = dict(progress or {})
        merged.update(fields)
        value = merged.get("sim_time_s")
        if isinstance(value, (int, float)) and math.isfinite(value):
            self.sim_time_s = max(self.sim_time_s, float(value))
        self.calls += 1
        if self.max_sim_s and self.sim_time_s >= self.max_sim_s:
            raise BenchStop(f"stopped at {self.sim_time_s:.3f} s simulated (--max-sim-s {self.max_sim_s:g})")


def _peak_rss_bytes() -> int:
    import resource
    return int(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss) * 1024


def _machine() -> dict:
    from .core.rundir import library_versions
    cpu = ""
    try:
        with open("/proc/cpuinfo", encoding="utf-8", errors="replace") as handle:
            cpu = next((line.split(":", 1)[1].strip() for line in handle if line.startswith("model name")), "")
    except OSError:
        pass
    from . import __version__
    return {"cpu": cpu or platform.processor(), "python": platform.python_version(), "cnctwin": __version__,
            **{k: v for k, v in library_versions().items() if k in ("numpy", "numba")}}


def run_example(spec: dict) -> dict:
    """One benchmark run in this process (the subprocess side): instrument, run, measure (module docstring)."""
    from .core.outputs import optional_entry, resolve_entry, run_document
    cpu0 = time.process_time()
    wall0 = time.perf_counter()
    timer = LevelTimer()
    probe = None
    table = spec.get("table")             # a level table of its own (tests); default: the loop's (level_table)
    if table is None:
        try:
            from .core.hot_abi import CNT_L0, CNT_TICKS
            probe = MacroProbe(CNT_L0, CNT_TICKS)
        except ImportError:
            probe = None
    installed, missing, restore = instrument(timer, probe, table)
    engine = spec.get("engine", "auto")
    run_dir = Path(spec["run_dir"])
    run_dir.mkdir(parents=True, exist_ok=True)
    progress = _Progress(spec.get("max_sim_s"))
    status, error, returned = "done", None, None
    try:
        runner = None
        if engine in ("auto", "loop"):
            named = engine == "loop" or spec.get("runner")
            runner = resolve_entry(spec.get("runner")) if named else optional_entry()
        if runner is None:
            engine, runner = "driver", drive_project
        elif engine == "auto":
            engine = "loop"
        returned = runner(Path(spec["project"]), run_dir, dict(spec.get("options") or {}), progress)
    except BenchStop as stop:
        status, error = "stopped", {"type": "BenchStop", "message": str(stop)}
    except Exception as failure:
        status, error = "failed", {"type": type(failure).__name__, "message": str(failure),
                                   "traceback": traceback.format_exc(limit=20)}
    finally:
        restore()
    cpu = time.process_time() - cpu0
    wall = time.perf_counter() - wall0
    simulated = progress.sim_time_s
    complete = (run_dir / "run.json").is_file()
    if isinstance(returned, dict) and isinstance(returned.get("simulated_s"), (int, float)):
        simulated = float(returned["simulated_s"])
    if complete:
        cycle = (run_document(run_dir).get("summary") or {}).get("cycle_time_s")
        if isinstance(cycle, (int, float)) and status == "done":
            simulated = float(cycle)
    result = {"format": RESULT_FORMAT, "version": 1, "example": spec["example"], "project": spec["project"],
              "engine": engine, "status": status, "error": error, "simulated_s": simulated, "wall_s": wall,
              "cpu_s": cpu, "cpu_per_sim": cpu / simulated if simulated > 0.0 else None,
              "peak_rss_bytes": _peak_rss_bytes(), "max_sim_s": spec.get("max_sim_s"),
              "levels": level_report(timer, probe, cpu, cpu0, simulated),
              "macro": probe.to_dict() if probe is not None else None, "instrumented": installed,
              "not_instrumented": missing, "run_complete": complete, "progress_calls": progress.calls,
              "machine": _machine(), "date": time.strftime("%Y-%m-%d", time.gmtime()), "outputs": None}
    if spec.get("outputs") and complete:
        result["outputs"] = outputs_timing(run_dir, spec.get("outputs_options"))
    return result


