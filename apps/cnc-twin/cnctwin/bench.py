# =============================================================================== the instrumenting profiler

class LevelTimer:
    """Process CPU time per level, each call booked exclusively: the time of a nested call of a wrapped function
    goes to that function's level only."""

    def __init__(self, clock=time.process_time) -> None:
        self.clock = clock
        self.cpu = {level: 0.0 for level in LEVELS}
        self.calls = {level: 0 for level in LEVELS}
        self.stack: list[list] = []
        self.first: float | None = None
        self.last: float | None = None

    def wrap(self, level: str, function):
        timer = self

        @functools.wraps(function)
        def timed(*args, **kwargs):
            start = timer.clock()
            if timer.first is None:
                timer.first = start
            timer.stack.append([level, 0.0])
            try:
                return function(*args, **kwargs)
            finally:
                end = timer.clock()
                _, nested = timer.stack.pop()
                elapsed = end - start
                timer.cpu[level] += elapsed - nested
                timer.calls[level] += 1
                if timer.stack:
                    timer.stack[-1][1] += elapsed
                timer.last = end

        timed.__wrapped_level__ = level
        return timed


class MacroProbe:
    """CPU, L0 steps and L1 ticks of every run_macro call (the hot loop's counters before and after the call)."""

    def __init__(self, l0_index: int, ticks_index: int, clock=time.process_time) -> None:
        self.l0_index, self.ticks_index, self.clock = l0_index, ticks_index, clock
        self.calls = 0
        self.cpu_s = 0.0
        self.ticks = 0
        self.l0_steps = 0
        self.free_cpu_s = 0.0       # calls without an L0 step: L1 alone
        self.free_ticks = 0

    def wrap(self, function):
        probe = self

        @functools.wraps(function)
        def run_macro(mi, rm, cs, ring, g):
            count = g.count
            l0, ticks = int(count[probe.l0_index]), int(count[probe.ticks_index])
            start = probe.clock()
            try:
                return function(mi, rm, cs, ring, g)
            finally:
                elapsed = probe.clock() - start
                dl0 = int(count[probe.l0_index]) - l0
                dticks = int(count[probe.ticks_index]) - ticks
                probe.calls += 1
                probe.cpu_s += elapsed
                probe.ticks += dticks
                probe.l0_steps += dl0
                if dl0 == 0:
                    probe.free_cpu_s += elapsed
                    probe.free_ticks += dticks

        return run_macro

    def l1_share_s(self) -> float | None:
        """Estimated L1 CPU inside run_macro: CPU per tick out of contact times all ticks (None without such
        calls)."""
        if self.free_ticks <= 0:
            return None
        return min(self.cpu_s, self.free_cpu_s / self.free_ticks * self.ticks)

    def to_dict(self) -> dict:
        return {"calls": self.calls, "cpu_s": self.cpu_s, "ticks": self.ticks, "l0_steps": self.l0_steps,
                "free_cpu_s": self.free_cpu_s, "free_ticks": self.free_ticks, "l1_share_s": self.l1_share_s()}


def _target(spec: str):
    """(owner, attribute, function) of ``module:function`` or ``module:Class.method``; None when not there."""
    module_name, _, qualname = spec.partition(":")
    try:
        module = importlib.import_module(module_name)
    except ImportError:
        return None
    owner = module
    parts = qualname.split(".")
    for part in parts[:-1]:
        owner = getattr(owner, part, None)
        if owner is None:
            return None
    raw = owner.__dict__.get(parts[-1]) if hasattr(owner, "__dict__") else None
    if raw is None or not (inspect.isfunction(raw) or callable(raw)) or isinstance(raw, (staticmethod, classmethod)):
        return None
    return owner, parts[-1], raw


def level_table() -> dict[str, list[str]]:
    """:data:`LEVEL_TABLE` plus the domains' slow-step methods found in ``cnctwin.<domain>.domain``: macro_step
    (L2), absorb (L2, except motion's (L1) and the hot-loop domains' (inside HotLoop._absorb)), end_operation and
    finalize (op ends)."""
    table = {level: list(LEVEL_TABLE[level]) for level in LEVELS}
    for domain in DOMAINS:
        name = f"cnctwin.{domain}.domain"
        try:
            module = importlib.import_module(name)
        except ImportError:
            continue
        for cls_name, cls in sorted(vars(module).items()):
            if not (inspect.isclass(cls) and cls.__module__ == name and cls_name.endswith("Domain")):
                continue
            for method, level in (("macro_step", "l2"), ("absorb", "l2"), ("end_operation", "op_end"),
                                  ("finalize", "op_end")):
                if method == "absorb" and domain in HOT_DOMAINS + ("motion",):
                    continue
                if inspect.isfunction(cls.__dict__.get(method)):
                    entry = f"{name}:{cls_name}.{method}"
                    if entry not in table[level]:
                        table[level].append(entry)
    return table


def instrument(timer: LevelTimer, probe: MacroProbe | None = None, table: dict | None = None):
    """Wrap every function of ``table`` (default :func:`level_table`) in place, and run_macro with ``probe``.
    Returns (installed, missing, restore): the specs wrapped, the specs not in this build, a function that puts
    the originals back."""
    table = level_table() if table is None else table
    installed, missing, originals = [], [], []
    for level in LEVELS:
        for spec in table.get(level, ()):
            found = _target(spec)
            if found is None:
                missing.append(spec)
                continue
            owner, attribute, function = found
            originals.append((owner, attribute, function))
            setattr(owner, attribute, timer.wrap(level, function))
            installed.append(spec)
    if probe is not None:
        found = _target(MACRO_KERNEL)
        if found is None:
            missing.append(MACRO_KERNEL)
        else:
            owner, attribute, function = found
            originals.append((owner, attribute, function))
            setattr(owner, attribute, timer.wrap("hot_loop", probe.wrap(function)))
            installed.append(MACRO_KERNEL)

    def restore() -> None:
        for owner, attribute, function in reversed(originals):
            setattr(owner, attribute, function)

    return installed, missing, restore


def level_report(timer: LevelTimer, probe: MacroProbe | None, cpu_total_s: float, cpu_start_s: float,
                 simulated_s: float) -> dict:
    """CPU seconds per level (the compiled L1 share moved from the hot loop to L1), ``other`` (in the loop, in no
    level), ``setup`` (before the first level call), ``finish`` (after the last), and each per simulated second."""
    cpu = dict(timer.cpu)
    share = probe.l1_share_s() if probe is not None else None
    if share is not None:
        cpu["hot_loop"] -= share
        cpu["l1"] += share
    first = timer.first if timer.first is not None else cpu_start_s + cpu_total_s
    last = timer.last if timer.last is not None else first
    setup = max(0.0, first - cpu_start_s)
    finish = max(0.0, cpu_start_s + cpu_total_s - last)
    loop = max(0.0, last - first)
    cpu["other"] = max(0.0, loop - sum(timer.cpu.values()))
    per_sim = {k: (v / simulated_s if simulated_s > 0.0 else None) for k, v in cpu.items()}
    return {"cpu_s": cpu, "per_sim": per_sim, "calls": dict(timer.calls), "setup_cpu_s": setup,
            "loop_cpu_s": loop, "finish_cpu_s": finish,
            "loop_per_sim": loop / simulated_s if simulated_s > 0.0 else None,
            "l1_split": "run_macro out of contact" if share is not None else
            ("no run_macro call without contact: its L1 share stays in the hot loop" if probe is not None and
             probe.calls else None)}


