def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="twin bench", description=__doc__.split("\n\n")[0])
    parser.add_argument("examples", nargs="*", help="example names (examples/<name>), project folders or files")
    parser.add_argument("--all", action="store_true", help="every example of examples/")
    parser.add_argument("--engine", choices=("auto", "loop", "driver"), default="auto",
                        help="loop: cnctwin.core.loop.run_project; driver: the hot-loop driver per operation; auto: "
                             "the loop when it is in the build")
    parser.add_argument("--runner", help="the run_project to use (module:function or /path/file.py:function)")
    parser.add_argument("--max-sim-s", type=float, help="stop each run after this much simulated time")
    parser.add_argument("--outputs", action="store_true", help="also time finalize_outputs on each finished run")
    parser.add_argument("--outputs-of", action="append", default=[], metavar="RUN_DIR",
                        help="time finalize_outputs on a copy of this run directory (repeatable)")
    parser.add_argument("--outputs-set", action="append", default=[], metavar="KEY=VALUE",
                        help="an outputs option for the timed finalize_outputs (JSON value; e.g. memory_mode=rlimit)")
    parser.add_argument("--memory-mode", choices=("auto", "systemd", "rlimit", "none"), default="auto")
    parser.add_argument("--memory", help="memory cap of a benchmark run (bytes or 2G; default bench.yaml)")
    parser.add_argument("--timeout", type=float, help="wall-time limit of a benchmark run (s)")
    parser.add_argument("--work", help="folder for the benchmark runs (default: a temporary folder)")
    parser.add_argument("--keep", action="store_true", help="keep the benchmark run directories")
    parser.add_argument("--doc", default=str(Path(paths.DOCS) / "performance.md"),
                        help="the performance document to update (default docs/performance.md)")
    parser.add_argument("--no-doc", action="store_true", help="do not update the performance document")
    parser.add_argument("--json", action="store_true", help="print the results as JSON")
    parser.add_argument("--child", help=argparse.SUPPRESS)
    parser.add_argument("--result", help=argparse.SUPPRESS)
    parser.add_argument("--memory-bytes", type=int, default=0, help=argparse.SUPPRESS)
    return parser


def _child(args) -> int:
    from .core.outputs import cap_memory
    from .core.rundir import write_json_atomic
    if args.memory_mode == "rlimit" and args.memory_bytes:
        cap_memory(int(args.memory_bytes))
    try:
        os.nice(max(0, 10 - os.nice(0)))
    except OSError:
        pass
    spec = json.loads(Path(args.child).read_text(encoding="utf-8"))
    result = run_example(spec)
    write_json_atomic(args.result, result)
    return 0


def _outputs_options(pairs) -> dict:
    outputs = {}
    for pair in pairs:
        key, _, text = pair.partition("=")
        try:
            outputs[key.strip()] = json.loads(text)
        except ValueError:
            outputs[key.strip()] = text
    return {"outputs": outputs} if outputs else {}


def main(argv=None) -> int:
    """Exit 0 when every run finished or stopped at ``--max-sim-s`` and every timed output generator succeeded,
    1 otherwise, 2 for a usage error."""
    args = build_parser().parse_args(argv)
    if args.child:
        return _child(args)
    if not args.examples and not args.all and not args.outputs_of:
        build_parser().print_usage(sys.stderr)
        sys.stderr.write("twin bench: name examples, --all, or --outputs-of RUN_DIR\n")
        return 2
    from .core.outputs import _bytes

    def say(line: str) -> None:
        if not args.json:
            sys.stderr.write(line + "\n")

    examples = find_examples(args.examples, args.all) if (args.examples or args.all) else []
    options = _outputs_options(args.outputs_set)
    results = bench(examples, engine=args.engine, runner=args.runner, max_sim_s=args.max_sim_s, outputs=args.outputs,
                    outputs_options=options, memory_mode=args.memory_mode,
                    memory_bytes=_bytes(args.memory, "memory") if args.memory else None, timeout_s=args.timeout,
                    work_dir=args.work, keep=args.keep, report=say) if examples else []
    outputs = bench_outputs(args.outputs_of, options, report=say) if args.outputs_of else []
    if not args.no_doc:
        written = write_doc(args.doc, results, outputs)
        say(f"wrote {written}")
    if args.json:
        sys.stdout.write(json.dumps({"runs": results, "outputs": outputs}, indent=1, default=str) + "\n")
    failed = [r for r in results if r.get("status") not in ("done", "stopped")]
    failed += [o for o in outputs if o["outputs"]["failed"]]
    failed += [r for r in results if r.get("outputs") and r["outputs"]["failed"]]
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())


