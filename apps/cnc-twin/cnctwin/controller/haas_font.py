def strokes(char: str) -> list[list[tuple[float, float]]] | None:
    """Polylines of one character in grid units, or None when the font lacks it."""
    spec = GLYPHS.get(char.upper())
    if spec is None:
        return None
    out = []
    for stroke in spec.split(";"):
        points = [tuple(float(v) for v in pair.split(",")) for pair in stroke.split()]
        if points:
            out.append(points)
    return out
